/** Core data model for Jason's Medical History. Mirrors the JSON files in the data root. */

export type RecordType =
  | 'visit'
  | 'lab'
  | 'imaging'
  | 'procedure'
  | 'vaccine'
  | 'medication'
  | 'hospital'
  | 'therapy'
  | 'document'

export const RECORD_TYPES: RecordType[] = [
  'visit',
  'lab',
  'imaging',
  'procedure',
  'vaccine',
  'medication',
  'hospital',
  'therapy',
  'document',
]

export const RECORD_TYPE_LABEL: Record<RecordType, string> = {
  visit: 'Visit',
  lab: 'Labs',
  imaging: 'Imaging',
  procedure: 'Procedure',
  vaccine: 'Vaccine',
  medication: 'Medication',
  hospital: 'Hospital',
  therapy: 'Therapy',
  document: 'Document',
}

/** How a finding should read at a glance. */
export type Sentiment = 'positive' | 'negative' | 'watch' | 'neutral'

export interface Finding {
  text: string
  sentiment: Sentiment
}

export interface LabValue {
  name: string
  value: number | string
  unit?: string
  /** Human-readable reference range, e.g. "< 100" or "4.0–10.5". */
  range?: string
  low?: number
  high?: number
  flag?: 'low' | 'high' | 'abnormal' | 'normal'
}

export interface Attachment {
  /** File name under attachments/<record-id>/ */
  file: string
  kind: 'image' | 'pdf' | 'document'
  label?: string
}

export interface Provider {
  name?: string
  specialty?: string
  facility?: string
}

export interface FollowUp {
  text: string
  due?: string
  done?: boolean
}

export interface MedRecord {
  id: string
  /** ISO date, YYYY-MM-DD */
  date: string
  /** When only the month or year is known, the day (and month) in `date` are placeholders. */
  datePrecision?: 'day' | 'month' | 'year'
  type: RecordType
  title: string
  provider?: Provider
  /** Episode id this record belongs to, if any. */
  episode?: string
  /** Episodes this record is connected to without being part of them, e.g. an early signal. */
  related?: { episode: string; note: string }[]
  /** Body areas this record concerns, e.g. "Left knee". Defaults to its episode's sites. */
  sites?: string[]
  /** Plain-English summary. */
  synopsis: string
  findings?: Finding[]
  /** Doctor's report as Markdown (inline). */
  report?: string
  /** Doctor's report as a file under attachments/<id>/ (md or pdf). */
  reportFile?: string
  attachments?: Attachment[]
  values?: LabValue[]
  tags?: string[]
  followUp?: FollowUp[]
  source?: { portal?: string; importedOn?: string; note?: string }
}

export type EpisodeStatus = 'active' | 'monitoring' | 'resolved'
export type EpisodeKind = 'injury' | 'condition' | 'screening' | 'procedure' | 'other'

export interface Episode {
  id: string
  title: string
  started: string
  /** When only the start year or month is known. */
  startedPrecision?: 'day' | 'month' | 'year'
  ended?: string
  status: EpisodeStatus
  kind: EpisodeKind
  summary: string
  tags?: string[]
  /** Body areas this episode concerns, e.g. ["Left knee"]. Used by the timeline's body-area filter. */
  sites?: string[]
  /** Other episodes this one is connected to, e.g. an injury that led to arthritis. Shown on both sides. */
  related?: { episode: string; note: string }[]
}

export interface Profile {
  name: string
  dob?: string
  bloodType?: string
  allergies?: { name: string; reaction?: string; severity?: string }[]
  medications?: { name: string; dose?: string; frequency?: string; since?: string; reason?: string }[]
  conditions?: { name: string; since?: string; status?: string }[]
  careTeam?: { name: string; role: string; facility?: string; phone?: string }[]
  screenings?: { name: string; last?: string; due?: string; note?: string }[]
  emergency?: { contact?: string; phone?: string; notes?: string }
}

/** Generated by scripts/build-index.mjs; the only JSON the app fetches on load. */
export interface DataIndex {
  generatedAt: string
  demo?: boolean
  profile: Profile
  episodes: Episode[]
  records: MedRecord[]
}
